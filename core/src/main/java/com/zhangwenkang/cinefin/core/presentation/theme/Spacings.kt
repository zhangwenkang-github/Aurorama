package com.zhangwenkang.cinefin.core.presentation.theme

import androidx.compose.ui.unit.dp

/**
 * 间距：以 4dp 为基准的少量档位。
 *
 * [default] 是页面左右留白（"页边"），所有内容都对齐到这条线； 卡片之间、区块之间用 [large] 拉开，靠留白而不是分隔框建立分区。
 */
object Spacings {
    val extraSmall = 4.dp
    val small = 8.dp
    val medium = 16.dp
    val default = 20.dp
    val large = 32.dp
    val extraLarge = 56.dp
}
